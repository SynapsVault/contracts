#![no_std]
//! SynapsVault — Subscription Manager (Soroban / Stellar)
//!
//! Manages recurring 30-day subscription plans for SynapsVault publishers.
//! Publishers create plans; the backend subscribes buyers after payment confirmation
//! and renews each billing cycle. Subscribers can self-cancel with access until period end.
//!
//! # Payment references
//!
//! `SubscribedEvent` and `RenewedEvent` carry a `payment_reference: String` that
//! backend and indexer clients use to correlate an on-chain event with an
//! off-chain payment. The contract treats the value as an **opaque, non-sensitive**
//! token: it is never parsed, compared, or stored, and it is emitted verbatim.
//!
//! ## Format
//!
//! - Encoding: ASCII, restricted to `[A-Za-z0-9_-]` (URL-safe base64 alphabet
//!   without padding). No whitespace, no `=`, no `+`/`/`.
//! - Length: 1..=`MAX_PAYMENT_REFERENCE_LEN` bytes (see constant below).
//! - Case: case-sensitive; clients MUST NOT case-fold references.
//! - Normalization: producers MUST emit the canonical form — no leading/trailing
//!   whitespace, no padding, no percent-encoding. Consumers SHOULD reject values
//!   that fail the character/length rules rather than silently normalizing them.
//!
//! ## Privacy
//!
//! References are **publicly visible** on-chain (event data is world-readable).
//! They MUST NOT contain PII (names, emails, phone numbers), raw account
//! identifiers (Stellar `G...`/`M...` addresses, card PANs, bank account numbers),
//! secrets, or anything that reveals the payer's identity. Use an opaque random
//! or hashed token generated by the backend (e.g. a UUIDv4 rendered as URL-safe
//! base64, or `HMAC(server_key, payment_id)` truncated to 32 bytes).
//!
//! ## Correlation
//!
//! - One reference per payment attempt; the same reference MUST NOT be reused
//!   across distinct payments.
//! - A `subscribe` event's reference identifies the initial payment; each
//!   `renew` event carries a fresh reference for that cycle's payment.
//! - To correlate, indexers join on `(plan_id, subscriber, payment_reference)`;
//!   the reference alone is not guaranteed unique across plans.
//!
//! ## Examples
//!
//! - `pay_9f2c1a7b4e8d4c3a` (prefixed random hex)
//! - `dG9rZW4tMTIzNDU2Nzg5MA` (URL-safe base64 of an opaque token, no padding)
//! - `hmac_3Q7xY2pL0aZk9VbN1cRf` (truncated HMAC tag)

use soroban_sdk::{
    contract, contracterror, contractevent, contractimpl, contracttype, Address, BytesN,
    ContractExecutable, Env, String,
};

/// Ledgers per day (~5 s per ledger).
const DAY: u32 = 17_280;

/// Length of one billing cycle in ledgers (30 days).
pub const CYCLE: u32 = 30 * DAY;

/// Maximum length of a plan identifier in bytes.
pub const MAX_PLAN_ID_LEN: u32 = 64;

/// Maximum length of a payment reference in bytes.
///
/// References are opaque, non-sensitive tokens (see the module docs for the
/// canonical format and privacy expectations).
pub const MAX_PAYMENT_REFERENCE_LEN: u32 = 64;

/// Maximum number of `(plan_id, subscriber)` pairs accepted by
/// [`check_subscriptions`] in a single call.
///
/// At 50 entries × ~1 persistent read each the worst-case ledger-entry budget
/// is well within the Soroban per-transaction limit. Callers with more than 50
/// pairs must paginate.
pub const MAX_BATCH_SIZE: u32 = 50;

/// Shared persistent-storage TTL policy (see `docs/CONTRACTS.md`).
const BUMP: u32 = 365 * DAY; // 1-year TTL
const BUMP_THRESH: u32 = BUMP - DAY;

/// Contract version, sourced from Cargo.toml at compile time.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// A recurring subscription plan offered by a publisher.
#[contracttype]
#[derive(Clone, Debug, PartialEq)]
pub struct Plan {
    pub plan_id: String,
    pub publisher: Address,
    pub price_per_cycle: i128,
    pub active: bool,
}

/// A subscriber's enrolment in a [`Plan`].
#[contracttype]
#[derive(Clone, Debug, PartialEq)]
pub struct Subscription {
    pub plan_id: String,
    pub subscriber: Address,
    pub started_at: u32,
    pub current_period_end: u32,
    pub cancelled: bool,
    pub total_renewals: u32,
}

/// The result of a single membership check in [`check_subscriptions`].
///
/// Mirrors `LeaseStatus` in `access-lease` with the vocabulary appropriate for
/// subscriptions:
///
/// - `Missing`  — no record exists for this `(plan_id, subscriber)` pair
///   (never subscribed, or subscription was cancelled and the record deleted).
/// - `Active(remaining)` — the subscription is live; `remaining` is the number
///   of ledgers until `current_period_end` (`current_period_end -
///   ledger.sequence()`). The subscription may be cancelled (`cancelled = true`)
///   but the paid window has not yet elapsed.
/// - `Expired`  — a record exists but `current_period_end ≤ ledger.sequence()`.
///
/// **Expiry boundary:** a subscription with `current_period_end ==
/// ledger.sequence()` returns `Expired`, not `Active` — consistent with the
/// exclusive-boundary rule used throughout this workspace.
#[contracttype]
#[derive(Clone, Debug, PartialEq)]
pub enum SubStatus {
    /// No subscription record for this pair.
    Missing,
    /// Subscription is live; value is ledgers remaining until period end.
    Active(u32),
    /// Record exists but the paid period has elapsed.
    Expired,
}

#[contracttype]
pub enum DataKey {
    Admin,
    Plan(String),
    Sub(String, Address),
    Version,
}

/// Subscription-manager error codes.
///
/// Numbering is **per-contract** and intentionally not aligned with the
/// `vault-registry` or `access-lease` enums: the same numeric value can mean
/// different things in different contracts (e.g. `AlreadyInitialised` is 9
/// here, 8 in the registry and 7 in the lease). The cross-contract mapping is
/// documented in `docs/CONTRACTS.md`; the discriminants are pinned by tests so
/// any renumbering is deliberate.
#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[repr(u32)]
pub enum Error {
    // 1 was NotAdmin, removed as it is never returned (admin auth traps on failure)
    PlanNotFound = 2,
    PlanInactive = 3,
    AlreadySubbed = 4,
    SubNotFound = 5,
    Cancelled = 6,
    InvalidPrice = 7,
    NotInitialised = 8,
    AlreadyInitialised = 9,
    PlanExists = 10,
    Overflow = 11,
    /// `plan_id` is empty or exceeds the maximum allowed length.
    InvalidPlanId = 12,
    /// The new admin address is the same as the current admin address.
    SameAdmin = 13,
    /// `check_subscriptions` received more than [`MAX_BATCH_SIZE`] pairs.
    BatchTooLarge = 14,
}

